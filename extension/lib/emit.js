  /* A double-quoted literal that is valid in Go, Java, Python and JavaScript alike. */
  function q(s) {
    return JSON.stringify(String(s))
      .replace(/\\ud[89a-f][0-9a-f]{2}/gi, '')
      .replace(/\u2028/g, '\\u2028')
      .replace(/\u2029/g, '\\u2029');
  }
  /* Request bodies are mostly JSON, which is full of double quotes. Where the language has a literal that
     needs no escaping for them, use it, so the generated tests stay readable. Anything unusual falls back to q(). */
  const PLAIN = /^[^\u0000-\u001f\u007f\u2028\u2029]*$/;
  function goLit(s) {
    s = String(s);
    return PLAIN.test(s) && !s.includes('`') ? '`' + s + '`' : q(s);
  }
  function pyLit(s) {
    s = String(s);
    if (!PLAIN.test(s) || s.includes("'") || s.endsWith('\\')) return q(s);
    return (s.includes('\\') ? 'r' : '') + "'" + s + "'";
  }
  function jsLit(s) {
    s = String(s);
    if (!PLAIN.test(s)) return q(s);
    return "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
  }
  const sh = (s) => "'" + String(s).replace(/'/g, "'\\''") + "'";
  const note = (s) => String(s).replace(/[\r\n\u2028\u2029]+/g, ' ').replace(/\\/g, '/');
  const cap = (w) => w.charAt(0).toUpperCase() + w.slice(1);
  const camel = (ws) => ws.map((w, i) => (i ? cap(w) : w)).join('');
  const envKey = (k) => 'API_TOKEN_' + String(k).toUpperCase().replace(/[^A-Z0-9]+/g, '_');
  const opW = (c) => c.words.slice(0, c.opLen);
  const restW = (c) => c.words.slice(c.opLen);
  const hasBody = (c) => c.body !== null && c.body !== '';

