  function emitCurl(plan) {
    const L = ['#!/usr/bin/env bash'].concat(
      header(plan, ['This script checks status codes only. Run:  API_BASE_URL=' + plan.baseUrl + ' API_TOKEN=... bash api-contract.sh'], '#')
    );
    L.push(
      'set -u',
      'BASE_URL="${API_BASE_URL:-' + plan.baseUrl.replace(/["$`\\]/g, '') + '}"',
      'BASE_URL="${BASE_URL%/}"',
      'pass=0; fail=0; skip=0',
      '',
      '# check NAME "WANTED CODES" METHOD PATH AUTH CONTENT_TYPE BODY [HEADER...]',
      'check() {',
      '  local name="$1" want="$2" method="$3" url="$BASE_URL$4" auth="$5" ctype="$6" body="$7" tok="" got',
      '  shift 7',
      "  local args=(-sS -o /dev/null -w '%{http_code}' --max-time 30 -H 'Accept: application/json')",
      '  if [ "$method" = "HEAD" ]; then args+=(--head); else args+=(-X "$method"); fi',
      '  while [ $# -gt 0 ]; do args+=(-H "$1"); shift; done',
      '  if [ -n "$ctype" ]; then args+=(-H "Content-Type: $ctype"); fi',
      '  if [ -n "$body" ]; then args+=(--data-binary "$body"); fi',
      '  if [ -n "$auth" ]; then',
      '    case "$auth" in'
    );
    for (const k of Object.keys(plan.auth)) L.push('      ' + sh(k) + ') tok="${' + envKey(k) + ':-${API_TOKEN:-}}" ;;');
    L.push(
      '      *) tok="${API_TOKEN:-}" ;;',
      '    esac',
      '    if [ -z "$tok" ]; then skip=$((skip + 1)); echo "SKIP $name (set API_TOKEN)"; return; fi',
      '    case "$auth" in'
    );
    for (const k of Object.keys(plan.auth)) {
      const a = plan.auth[k];
      if (a.in === 'query') {
        const pair = sh(encodeURIComponent(a.name) + '=');
        L.push('      ' + sh(k) + ') case "$url" in *\\?*) url="$url&"' + pair + '"$tok" ;; *) url="$url?"' + pair + '"$tok" ;; esac ;;');
      } else {
        L.push('      ' + sh(k) + ') args+=(-H ' + sh(a.name + ': ' + a.prefix) + '"$tok") ;;');
      }
    }
    L.push(
      '      *) ;;',
      '    esac',
      '  fi',
      '  got="$(curl "${args[@]}" "$url")" || got="000"',
      '  case " $want " in',
      '    *" $got "*) pass=$((pass + 1)); echo "PASS $name" ;;',
      '    *) fail=$((fail + 1)); echo "FAIL $name: status $got, want one of: $want" ;;',
      '  esac',
      '}',
      ''
    );
    for (const c of plan.cases) {
      const a = [sh(note(c.title)), sh(c.expect.status.join(' ')), sh(c.method), sh(c.path), sh(c.auth || ''), sh(hasBody(c) ? c.contentType : ''), sh(c.body || '')];
      for (const h of c.headers) a.push(sh(h[0] + ': ' + h[1]));
      if (c.expect.assumed) L.push('# assumed: the contract documents no response for this case');
      L.push('check ' + a.join(' '));
    }
    L.push('', 'echo "$pass passed, $fail failed, $skip skipped"', '[ "$fail" -eq 0 ]', '');
    return { file: 'api-contract.sh', code: L.join('\n'), run: 'API_BASE_URL=' + plan.baseUrl + ' API_TOKEN=... bash api-contract.sh', needs: 'bash and curl. Checks status codes only, not response fields.' };
  }

