      L.push('      case ' + q(k) + ': // ' + note(a.hint));
      if (a.in === 'query') L.push('        return target + (target.contains("?") ? "&" : "?") + ' + q(encodeURIComponent(a.name) + '=') + ' + URLEncoder.encode(tok, StandardCharsets.UTF_8);');
